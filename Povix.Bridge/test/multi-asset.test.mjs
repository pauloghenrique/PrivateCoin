import test from 'node:test';
import assert from 'node:assert/strict';
import ganache from 'ganache';
import { BrowserProvider, Wallet, ContractFactory, Contract } from 'ethers';
import { mkdtempSync, readFileSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { compile, root } from '../src/compile.mjs';
import { types, domain, networkHash, sortSignatures, journal, native, prepareMint, representationId, nativeSymbol, validateConfig } from '../src/bridge.mjs';
const mono = process.env.POVIX_MONO || 'mono';
const read = file => JSON.parse(readFileSync(file, 'utf8'));

test('multi-asset source identity, six decimal issuance, replay and isolated redemption', { timeout: 900000 }, async () => {
 const dir=mkdtempSync(path.join(tmpdir(),'povix-multi-'));
 const rpc=ganache.provider({chain:{chainId:31337},logging:{quiet:true},wallet:{totalAccounts:6}});
 const provider=new BrowserProvider(rpc,undefined,{cacheTimeout:-1}); provider.pollingInterval=10;
 let db;
 try {
  const run=(exe,...args)=>execFileSync(mono,[path.join(root,'build/native/'+exe+'.exe'),...args],{encoding:'utf8',timeout:240000});
  console.log(run('BridgeNativeRegression','setup',dir).trim());
  const wallets=Object.values(rpc.getInitialAccounts()).map(a=>new Wallet(a.secretKey));
  const signer=await provider.getSigner(0), mock=compile('test/MockAsset.sol','MockAsset'), artifact=compile();
  const deployToken=async p=>{const t=await new ContractFactory(mock.abi,mock.bytecode,signer).deploy(p);await t.waitForDeployment();return t;};
  const unsupported=await deployToken(19);
  const primary=await deployToken(18), a=await deployToken(6), b=await deployToken(18), zero=await deployToken(0);
  const config={...read(path.join(dir,'native-config.json')),asset:(await primary.getAddress()).toLowerCase(),operators:wallets.slice(0,3).map(w=>w.address),threshold:2,bscConfirmations:15,reserveCap:'1000000000',dailyReleaseCap:'100000000',nativeSnapshot:path.join(dir,'chain.json'),rpcUrl:'http://127.0.0.1:8545'};
  const baseVault=await new ContractFactory(artifact.abi,artifact.bytecode,signer).deploy(config.asset,networkHash(config),'0x'+config.nativeToken,config.operators,2,config.reserveCap,config.dailyReleaseCap); await baseVault.waitForDeployment();
  config.bridge=(await baseVault.getAddress()).toLowerCase();writeFileSync(path.join(dir,'config.json'),JSON.stringify(config));
  run('BridgeNativeRegression','configure',dir);
  const fa=compile('contracts/AssetVaultFactory.sol','AssetVaultFactory');
  const factory=await new ContractFactory(fa.abi,fa.bytecode,signer).deploy(config.bridge);await factory.waitForDeployment();
  const addr=(await a.getAddress()).toLowerCase(), other=(await b.getAddress()).toLowerCase();
  assert.equal(await factory.representation(config.asset),'0x'+config.nativeToken);
  assert.equal(await a.symbol(),await b.symbol());
  assert.notEqual(representationId(31337,addr),representationId(31337,other));
  assert.notEqual(representationId(97,addr),representationId(31337,addr));
  assert.equal(await factory.representation(addr),'0x'+representationId(31337,addr));
  for(const token of [a,b,zero]) await (await factory.createVault(await token.getAddress())).wait();
  await assert.rejects(factory.createVault(addr));
  await assert.rejects(factory.createVault(await unsupported.getAddress()));
  await assert.rejects(factory.createVault("0x"+"0".repeat(40)));
  const vaultAddress=(await factory.vaults(addr)).toLowerCase(), vault=new Contract(vaultAddress,artifact.abi,signer);
  const second=new Contract(await factory.vaults(other),artifact.abi,signer);
  const zeroVault=new Contract(await factory.vaults(await zero.getAddress()),artifact.abi,signer);
  assert.equal(await zeroVault.nativeDecimals(),0n);assert.equal(await zeroVault.scale(),1n);
  assert.equal(await vault.nativeDecimals(),6n);assert.equal(await vault.scale(),1n);assert.equal(await second.scale(),10000000000n);
  const assetConfig={...config,asset:addr,bridge:vaultAddress,nativeToken:representationId(31337,addr),nativeDecimals:6,nativeSymbol:nativeSymbol(await a.symbol())};validateConfig(assetConfig);
  const deadline=Math.floor(Date.now()/1000)+600;
  const pause={paused:false,nonce:'0',deadline};
  const pauseSignatures=await Promise.all(wallets.slice(0,2).map(w=>w.signTypedData(domain(assetConfig),{Pause:types.Pause},pause)));
  await (await vault.setPaused(false,deadline,sortSignatures(assetConfig,'Pause',pause,pauseSignatures))).wait();
  assert.equal(await second.paused(),true);
  const holder=readFileSync(path.join(dir,'holder.txt'),'utf8');
  await (await a.approve(vaultAddress,1250000n)).wait();
  const receipt=await (await vault.deposit(1250000n,'0x'+holder)).wait();
  const log=receipt.logs.find(l=>{try{return vault.interface.parseLog(l)?.name==='Deposited';}catch{return false;}});
  for(let i=0;i<14;i++)await rpc.request({method:'evm_mine',params:[]});
  db=journal(path.join(dir,'multi.sqlite'),assetConfig);
  const reference={transactionHash:receipt.hash,logIndex:log.index};
  const batch=await prepareMint(db,provider,vault,assetConfig,reference,path.join(dir,'admin-keys.local.json'),0);
  assert.equal(batch.transactions.length,2);assert.equal(batch.transactions[0].Token.Supply,0);assert.equal(batch.transactions[1].TokenCommand.Amount,1250000);
  assert.deepEqual(await prepareMint(db,provider,vault,assetConfig,reference,path.join(dir,'admin-keys.local.json'),0),batch);
  writeFileSync(path.join(dir,'asset-config.json'),JSON.stringify(assetConfig));writeFileSync(path.join(dir,'issuance.json'),JSON.stringify(batch.transactions));
  console.log(run('MultiAssetNativeRegression','confirm-first',dir).trim());
  console.log(run('MultiAssetNativeRegression','burn',dir,wallets[4].address.toLowerCase()).trim());
  const evidence=read(path.join(dir,'multi-evidence.json'));
  const value={burnId:evidence.depositId,recipient:evidence.recipient,nativeAmount:evidence.amount,deadline};
  const signatures=await Promise.all(wallets.slice(0,2).map(w=>w.signTypedData(domain(assetConfig),{Release:types.Release},value)));
  const ordered=sortSignatures(assetConfig,'Release',value,signatures);
  // A quorum for asset A cannot release tokens from asset B's independent vault.
  await assert.rejects(second.release(value.burnId,value.recipient,value.nativeAmount,value.deadline,ordered));
  await (await vault.release(value.burnId,value.recipient,value.nativeAmount,value.deadline,ordered)).wait();
  assert.equal(await a.balanceOf(wallets[4].address),250000n);assert.equal(await vault.accountedReserve(),1000000n);assert.equal(await second.accountedReserve(),0n);
  await assert.rejects(vault.release(value.burnId,value.recipient,value.nativeAmount,value.deadline,ordered));
  db.close();db=journal(path.join(dir,'multi.sqlite'),assetConfig);
  assert.deepEqual(await prepareMint(db,provider,vault,assetConfig,reference,path.join(dir,'admin-keys.local.json'),0),batch);
 } finally {if(db)db.close();await provider.destroy();await rpc.disconnect();rmSync(dir,{recursive:true,force:true});}
});
